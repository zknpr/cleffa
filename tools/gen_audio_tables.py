"""Emit the pinned Omni frontend's Hann window and sparse Slaney filter bank."""
import hashlib
import json
from pathlib import Path
import sys

import torch
import transformers
from transformers import WhisperFeatureExtractor

ROOT=Path(__file__).resolve().parents[1]
REVISION='0db1cd2607d76a7bdb2a382f659e7b313079f84b'


def main():
    if torch.__version__.split('+')[0] != '2.11.0' or transformers.__version__ != '5.10.2':
        raise ValueError('audio tables require torch 2.11.0 and transformers 5.10.2')
    path=ROOT/'model-omni/processor_config.json'
    data=path.read_bytes()
    expected=json.loads((ROOT/'tools/snapshots'/f'{REVISION}.json').read_text())['files']['processor_config.json']
    actual=hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()
    if len(data) != expected['size'] or actual != expected['hash']:
        raise ValueError('processor config differs from pinned snapshot')
    config=json.loads(data)['feature_extractor']
    extractor=WhisperFeatureExtractor(**config)
    window=torch.hann_window(400).numpy()
    filters=extractor.mel_filters.astype('float32')
    entries,offsets=[],[0]
    for mel in range(128):
        entries.extend((f,float(filters[f,mel])) for f in range(201) if filters[f,mel] != 0)
        offsets.append(len(entries))
    print(f'/* Generated by tools/gen_audio_tables.py; Omni {REVISION}.')
    print(' * torch 2.11.0 CPU Hann; transformers 5.10.2 float32 Slaney filters. */')
    print('static const float audio_hann[400] = {')
    for start in range(0,400,4):print('    '+', '.join(float(v).hex()+'f' for v in window[start:start+4])+',')
    print('};\nstatic const uint16_t audio_mel_offsets[129] = {')
    for start in range(0,129,16):print('    '+', '.join(map(str,offsets[start:start+16]))+',')
    print('};\nstatic const struct { uint16_t bin; float weight; } audio_mel_filters[] = {')
    for f,value in entries:print(f'    {{{f}, {value.hex()}f}},')
    print('};')


if __name__=='__main__': main()
